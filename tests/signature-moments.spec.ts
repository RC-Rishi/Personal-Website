import { test, expect, type Page } from '@playwright/test'
test.setTimeout(45000)
const host = (page: Page) => page.locator('.signature-moments')
async function load(page: Page) {
  await page.goto('/?component=signature-moments')
  await expect(host(page)).toHaveAttribute('data-ready', 'true')
}
async function go(page: Page, index = 0) {
  await host(page).evaluate((el, index) => window.scrollTo({ top: el.getBoundingClientRect().top + scrollY + Number(el.dataset.entranceDistance) + Number(el.dataset.step) * index, behavior: 'instant' }), index)
  await expect(host(page)).toHaveAttribute('data-phase', 'moments')
  await expect(host(page)).toHaveAttribute('data-current', String(index))
  await expect(host(page)).toHaveAttribute('data-motion', 'resting')
}
async function playing(page: Page) {
  await expect.poll(() => page.locator('video').evaluate(v => (v as HTMLVideoElement).readyState >= 3 && !(v as HTMLVideoElement).paused)).toBe(true)
  const time = await page.locator('video').evaluate(v => (v as HTMLVideoElement).currentTime)
  await expect.poll(() => page.locator('video').evaluate(v => (v as HTMLVideoElement).currentTime)).toBeGreaterThan(time)
}

test('entrance lands, scrolling reverses, and navigation stays inside the viewport', async ({ page }, info) => {
  const errors: string[] = [], external: string[] = [], clips: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    if (request.url().startsWith('http') && !request.url().includes('127.0.0.1')) external.push(request.url())
    if (request.url().endsWith('.mp4')) clips.push(request.url())
  })
  await load(page)
  await expect(page.getByRole('button', { name: 'Explore signature moments' })).toBeVisible()
  await host(page).evaluate(el => window.scrollTo({ top: Number(el.dataset.entranceDistance) * .4, behavior: 'instant' }))
  await expect(page.locator('.signature-flight')).toBeVisible()
  const center = await page.locator('.signature-flight').boundingBox()
  expect(center!.width).toBeGreaterThan(80)
  await go(page, 2)
  await expect(page.locator('.signature-flight')).toBeHidden()
  const rect = await page.getByRole('button', { name: 'Open The Catch', exact: true }).boundingBox()
  expect(rect!.x).toBeGreaterThan(0)
  expect(rect!.x + rect!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: `artifacts/signature-validation/verified-field-${info.project.name}.png` })
  await page.getByRole('button', { name: 'Show moment 5 of 5' }).click()
  await expect(host(page)).toHaveAttribute('data-current', '4')
  await go(page, 0)
  await page.locator('.signature-pin').focus()
  await page.keyboard.press('ArrowRight')
  await expect(host(page)).toHaveAttribute('data-current', '1')
  await expect(page.getByRole('button', { name: 'Open Single Season Record' })).toBeFocused()
  await page.keyboard.press('End')
  await expect(host(page)).toHaveAttribute('data-current', '4')
  await page.keyboard.press('Home')
  await expect(host(page)).toHaveAttribute('data-current', '0')
  await host(page).evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await expect(page.getByRole('button', { name: 'Explore signature moments' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([]); expect(external).toEqual([]); expect(clips).toEqual([])
})

test('card flips into real playback, controls work, and closing restores focus and stops audio', async ({ page }, info) => {
  const errors: string[] = [], requested: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.url().endsWith('.mp4')) requested.push(request.url()) })
  await load(page); await go(page, 2)
  const card = page.getByRole('button', { name: 'Open The Catch', exact: true })
  await card.focus(); await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await playing(page)
  await page.waitForTimeout(850)
  const video = page.locator('video')
  const bounds = await video.boundingBox(), viewport = page.viewportSize()!
  expect(bounds!.x).toBeGreaterThanOrEqual(0); expect(bounds!.y).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(viewport.width + 1)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(viewport.height + 1)
  expect(bounds!.width / bounds!.height).toBeCloseTo(16 / 9, 1)
  await page.getByRole('button', { name: 'Pause', exact: true }).click({ force: true })
  await expect.poll(() => video.evaluate(v => (v as HTMLVideoElement).paused)).toBe(true)
  await page.getByRole('slider', { name: 'Seek' }).fill('10')
  await expect.poll(() => video.evaluate(v => (v as HTMLVideoElement).currentTime)).toBeGreaterThanOrEqual(9.8)
  await page.getByRole('button', { name: 'Mute', exact: true }).click({ force: true })
  await expect.poll(() => video.evaluate(v => (v as HTMLVideoElement).muted)).toBe(true)
  await page.getByRole('button', { name: 'Unmute', exact: true }).click({ force: true })
  await page.getByRole('button', { name: 'Play', exact: true }).click({ force: true })
  await playing(page)
  await page.screenshot({ path: `artifacts/signature-validation/verified-player-${info.project.name}.png` })
  await page.getByRole('button', { name: 'Close video' }).focus()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Enter fullscreen' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Close video' })).toBeFocused()
  await video.evaluate(v => { (window as unknown as { retiredVideo: HTMLVideoElement }).retiredVideo = v as HTMLVideoElement })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.evaluate(() => (window as unknown as { retiredVideo: HTMLVideoElement }).retiredVideo.paused)).toBe(true)
  await expect(card).toBeFocused()
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
  expect(requested.every(url => url.endsWith('moment-03.mp4'))).toBe(true)
  expect(errors).toEqual([])
})

test('horizontal dragging moves cards without accidentally opening playback; vertical touch stays native', async ({ page, isMobile }) => {
  await load(page); await go(page, 0)
  const bounds = await page.getByRole('button', { name: 'Open The Peach Bowl' }).boundingBox()
  const x = bounds!.x + bounds!.width * .7, y = bounds!.y + bounds!.height * .5
  if (isMobile) {
    const session = await page.context().newCDPSession(page)
    await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
    for (let i = 1; i <= 12; i++) {
      await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x - i * 16, y: y + 1 }] })
      await page.waitForTimeout(25)
    }
    await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect(host(page)).toHaveAttribute('data-dragging', 'false')
    await expect.poll(async () => Number(await host(page).getAttribute('data-position'))).toBeGreaterThan(.5)
    await page.waitForTimeout(600)
    const before = await page.evaluate(() => scrollY)
    await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 195, y: 500 }] })
    for (let i = 1; i <= 10; i++) {
      await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 196, y: 500 - i * 16 }] })
      await page.waitForTimeout(25)
    }
    await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(before + 30)
    await session.detach()
  } else {
    await page.mouse.move(x, y); await page.mouse.down()
    await page.mouse.move(x - 300, y + 1, { steps: 15 })
    await expect(host(page)).toHaveAttribute('data-dragging', 'true')
    await page.mouse.up()
    await expect(host(page)).toHaveAttribute('data-dragging', 'false')
    await expect.poll(async () => Number(await host(page).getAttribute('data-position'))).toBeGreaterThan(.5)
  }
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

