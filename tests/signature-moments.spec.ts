test('render scheduling rests when idle and hidden; media pauses on visibility changes', async ({ page }) => {
  await load(page); await go(page, 2)
  const renders = await host(page).getAttribute('data-render-count')
  await page.waitForTimeout(220)
  expect(await host(page).getAttribute('data-render-count')).toBe(renders)
  await page.getByRole('button', { name: 'Open The Catch', exact: true }).click({ force: true })
  await playing(page)
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')) })
  await expect(host(page)).toHaveAttribute('data-active', 'false')
  await expect.poll(() => page.locator('video').evaluate(v => (v as HTMLVideoElement).paused)).toBe(true)
  const hiddenRenders = await host(page).getAttribute('data-render-count')
  await page.waitForTimeout(150)
  expect(await host(page).getAttribute('data-render-count')).toBe(hiddenRenders)
  await page.evaluate(() => { Reflect.deleteProperty(document, 'hidden'); document.dispatchEvent(new Event('visibilitychange')) })
  await playing(page)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.locator('.signature-demo-end').scrollIntoViewIfNeeded()
  await expect(host(page)).toHaveAttribute('data-active', 'false')
  expect(await page.locator('.signature-float').first().evaluate(el => { const css = getComputedStyle(el); return css.animationName === 'none' || css.animationPlayState === 'paused' })).toBe(true)
})

test('blocked audible autoplay falls back to muted playback and keeps a usable unmute control', async ({ page }) => {
  await page.addInitScript(() => {
    const play = HTMLMediaElement.prototype.play
    HTMLMediaElement.prototype.play = function () {
      return !this.muted ? Promise.reject(new DOMException('Gesture required', 'NotAllowedError')) : Reflect.apply(play, this, [])
    }
  })
  await load(page); await go(page, 2)
  await page.getByRole('button', { name: 'Open The Catch', exact: true }).click({ force: true })
  await playing(page)
  await expect(page.getByRole('button', { name: 'Unmute', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Unmute', exact: true }).click()
  await expect.poll(() => page.locator('video').evaluate(v => (v as HTMLVideoElement).muted)).toBe(false)
  await page.keyboard.press('Escape')
})

